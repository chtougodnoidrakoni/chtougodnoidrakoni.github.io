const v = (x: Record<string, string>, k: string, fb: string) => (x[k]?.trim() ? x[k]!.trim() : fb);

export function buildPrompt(game: GameSystem, x: Record<string, string>): string {
  return buildText(game, x) + '\n' + aiSkeleton(game);
}
